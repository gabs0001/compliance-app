CREATE OR REPLACE TRIGGER TRG_LICENSE_STATUS
BEFORE INSERT OR UPDATE ON TB_ENVIRONMENTAL_LICENSE
FOR EACH ROW
BEGIN
    IF :NEW.EXPIRATION_DATE < SYSDATE THEN
        :NEW.STATUS := 'EXPIRED';

INSERT INTO TB_ENVIRONMENTAL_ALERT (TYPE, DESCRIPTION, REFERENCE_ID, REFERENCE_TYPE)
VALUES (
           'LICENSE_EXPIRED',
           'Environmental license expired',
           :NEW.ID,
           'LICENSE'
       );

ELSIF :NEW.EXPIRATION_DATE <= SYSDATE + 30 THEN
        :NEW.STATUS := 'EXPIRING_SOON';

INSERT INTO TB_ENVIRONMENTAL_ALERT (TYPE, DESCRIPTION, REFERENCE_ID, REFERENCE_TYPE)
VALUES (
           'LICENSE_EXPIRING_SOON',
           'Environmental license expiring within 30 days',
           :NEW.ID,
           'LICENSE'
       );

ELSE
        :NEW.STATUS := 'VALID';
END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_EMISSION_ALERT
BEFORE INSERT OR UPDATE ON TB_CARBON_EMISSION
FOR EACH ROW
BEGIN
    IF :NEW.AMOUNT > :NEW.LIMIT_VALUE THEN
        :NEW.STATUS := 'ABOVE_LIMIT';

INSERT INTO TB_ENVIRONMENTAL_ALERT (TYPE, DESCRIPTION, REFERENCE_ID, REFERENCE_TYPE)
VALUES (
           'EMISSION_ABOVE_LIMIT',
           'Carbon emission exceeded allowed limit',
           :NEW.ID,
           'EMISSION'
       );
ELSE
        :NEW.STATUS := 'NORMAL';
END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_AUDIT_ALERT
AFTER INSERT ON TB_ENVIRONMENTAL_AUDIT
FOR EACH ROW
BEGIN
    IF :NEW.RESULT = 'IRREGULAR' THEN
        INSERT INTO TB_ENVIRONMENTAL_ALERT (TYPE, DESCRIPTION, REFERENCE_ID, REFERENCE_TYPE)
        VALUES (
            'AUDIT_IRREGULAR',
            'Audit registered with irregular result',
            :NEW.ID,
            'AUDIT'
        );
END IF;
END;
